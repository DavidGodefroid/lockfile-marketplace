func TestNoAnswer(t *testing.T) {
	harness.CheckNoAnswer(t, ".", map[string][]byte{
		"sample.txt": pdfxtest.Sample,
		"empty":      nil,
		"op-not-boolean.pdf": pdfxtest.Write(pdfxtest.Doc{
			Pages:   []pdfxtest.Page{{Content: "BT /F1 12 Tf 72 720 Td (sample) Tj ET", Resources: "<< /Font << /F1 " + pdfxtest.Helvetica + " >> >>"}},
			Objects: []string{"<< /Type /ExtGState /OP 1 >>"},
		}),
	})
}
